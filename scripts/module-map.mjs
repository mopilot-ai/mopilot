// Generates docs/module-map.md: every source file with the first sentence of its header comment, grouped by
// folder, so an agent can find where something lives without reading the tree. The map is not committed (.gitignore):
// `npm ci` writes it (the prepare script), and it changed in most merges when it was. --check is the guard that stays:
// every source file has a header comment (the pre-commit hook and the unit-tests check run it).
//
//   npm run module-map              (write docs/module-map.md)
//   npm run module-map -- --stdout  (print the map instead)
//   npm run module-map -- --check   (exit 1, naming them, when a source file has no header comment)
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { treeFiles } from './source-tree.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
export const OUT = 'docs/module-map.md';
const DIRS = ['electron', 'shared', 'relay', 'host', 'src', 'scripts', 'bench', 'core', 'mobile/src'];
const SOURCE = /\.(?:[cm]?js|[cm]?ts|tsx|rs)$/;
// generated protocol types and declaration files describe other modules; they have no behavior of their own
const SKIP = /^src\/protocol\/|\.d\.[cm]?ts$/;

/** Repository-relative source files, sorted. */
export function sourceFiles(repoRoot = root) {
  // the core's Cargo build output (core/target) is not source
  const skip = (/** @type {string} */ p, /** @type {boolean} */ isDirectory) => isDirectory && path.basename(p) === 'target';
  return DIRS.flatMap((dir) =>
    treeFiles(path.join(repoRoot, dir), SOURCE, { skip }).map((p) => path.relative(repoRoot, p).split(path.sep).join('/')),
  )
    .filter((rel) => !SKIP.test(rel))
    .sort();
}

/**
 * The first sentence of a file's header: the `//` lines it starts with (Rust's `//!` inner doc comments too), or a block comment it starts with that a
 * blank line separates from the code (a block right above a declaration documents that declaration instead).
 * Null when the file has no header.
 */
export function summary(text) {
  const lines = text.replace(/^#!.*\n/, '').split('\n');
  let i = 0;
  while (i < lines.length && /^\s*(?:(['"])use strict\1;?|\/\/\s*@ts-check)\s*$/.test(lines[i])) i++;
  let body = '';
  if (/^\s*\/\//.test(lines[i] ?? '')) {
    while (i < lines.length && /^\s*\/\//.test(lines[i])) body += ` ${lines[i++].replace(/^\s*\/\/!?\s?/, '')}`;
  } else if (/^\s*\/\*/.test(lines[i] ?? '')) {
    const start = i;
    while (i < lines.length && !lines[i].includes('*/')) i++;
    if (i >= lines.length || (lines[i + 1] ?? '').trim() !== '') return null;
    body = lines
      .slice(start, i + 1)
      .join(' ')
      .replace(/\/\*+|\*+\//g, '')
      .replace(/^\s*\*\s?/gm, '')
      .replace(/\s\*\s/g, ' ');
  }
  const flat = body.replace(/\s+/g, ' ').trim();
  if (!flat) return null;
  const sentence = /^.*?[.!?](?=\s|$)/.exec(flat)?.[0] ?? flat;
  return sentence.length > 220 ? `${sentence.slice(0, 217)}...` : sentence;
}

/** The markdown for these files and their summaries. */
export function render(entries) {
  const byDir = new Map();
  for (const [file, text] of entries) {
    const dir = path.posix.dirname(file);
    if (!byDir.has(dir)) byDir.set(dir, []);
    byDir.get(dir).push(`- \`${path.posix.basename(file)}\`: ${text ?? '(no header comment)'}`);
  }
  const out = [
    '# Module map',
    '',
    "Generated by `npm run module-map` from each file's header comment and not committed; do not edit it. Give a new",
    'file a one-line header comment saying what it owns, and run `npm run module-map` to see it here.',
  ];
  for (const [dir, rows] of byDir) out.push('', `## ${dir}`, '', ...rows);
  return `${out.join('\n')}\n`;
}

/** Each source file with its header's first sentence (null without one). */
const entries = (repoRoot = root) => sourceFiles(repoRoot).map((file) => [file, summary(readFileSync(path.join(repoRoot, file), 'utf8'))]);

export function generate(repoRoot = root) {
  return render(entries(repoRoot));
}

/** Source files without a header comment. */
export function missingHeaders(repoRoot = root) {
  return entries(repoRoot)
    .filter(([, text]) => text === null)
    .map(([file]) => file);
}

/**
 * The command line: `--check` fails when a source file has no header comment, `--stdout` prints the map, and with
 * neither it writes docs/module-map.md. 0, or 1 with the reason on stderr.
 * @param {string[]} args
 * @param {{ repoRoot?: string, log?: (text: string) => void, logError?: (text: string) => void }} [deps]
 */
export function cli(args, { repoRoot = root, log = (text) => process.stdout.write(text), logError = console.error } = {}) {
  if (args.includes('--check')) {
    const missing = missingHeaders(repoRoot);
    if (!missing.length) return 0;
    logError(
      `These source files have no header comment; give each a one-line comment saying what it owns:\n${missing.map((f) => `  ${f}`).join('\n')}`,
    );
    return 1;
  }
  const text = generate(repoRoot);
  if (args.includes('--stdout')) {
    log(text);
    return 0;
  }
  const file = path.join(repoRoot, OUT);
  mkdirSync(path.dirname(file), { recursive: true });
  // an unchanged map is left alone, so its timestamp says when it last changed
  if (!existsSync(file) || readFileSync(file, 'utf8') !== text) writeFileSync(file, text);
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = cli(process.argv.slice(2));
