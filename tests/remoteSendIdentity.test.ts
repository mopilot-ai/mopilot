// Ordinary sends share MoMo's durable reservation rules, preserve v1 receipts and distinguish structured identities.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import path from 'node:path';
import { rig } from './support/remote-kit.ts';
import { fs, tempDir } from './support/remoteKit.ts';
import { waitFor } from './support/waitFor.ts';

const require = createRequire(import.meta.url);
const { SendLedger } = require('../electron/remote/sendLedger.cjs');
const call = (r: ReturnType<typeof rig>, params: any, pair = 'p1') =>
  r.service.call(r.service.phones.get(pair).client, 'chat.send', params);

test('historically produced v1 completed and pending entries retain their meaning after the structured-key upgrade', async () => {
  // Generated by the pre-change method, parser and ledger at this exact commit, not by the current writer.
  const historical = JSON.parse(await fs.readFile(new URL('./fixtures/remote-send-ledger-v1.json', import.meta.url), 'utf8'));
  assert.equal(historical.producerCommit, '5c459c408e8d4605dbad7d84b8ef0b5399349898');
  assert.deepEqual(historical.sourceBlobs, {
    'electron/remote/methods/chat.cjs': '54b041935f831f76d115252816c737d8644001de',
    'electron/remote/sendLedger.cjs': 'b45761c0f12b6fbed1e6a4c6e11a1c0bed856923',
    'shared/remote/schema.mjs': '40eabc122e00b2ef6f0888b1a26c344e1473857e',
  });
  const file = path.join(tempDir(), 'sends.json');
  await fs.writeFile(file, JSON.stringify(historical.record));
  const r = rig();
  (r.link.mac as any).sendLedger = new SendLedger({ file, fs });
  assert.deepEqual(await call(r, historical.completed), historical.receipt);
  assert.equal(r.calls.filter((c) => c[0] === 'send').length, 0);
  await assert.rejects(call(r, { ...historical.completed, text: 'changed' }), { code: 'send_conflict' });
  // Reopen on every retry: even the second or Nth process never erases the historical pending reservation.
  for (let n = 0; n < 4; n++) {
    (r.link.mac as any).sendLedger = new SendLedger({ file, fs });
    await assert.rejects(call(r, historical.pending), { code: 'send_uncertain' });
  }
  assert.equal(r.calls.filter((c) => c[0] === 'send').length, 0);
  await call(r, historical.pending, 'p2');
  assert.equal(r.calls.filter((c) => c[0] === 'send').length, 1, 'another pair never receives p1’s receipt');
});

test('ordinary canonical fingerprints ignore property ordering/deadline but preserve all delivery inputs', async () => {
  const r = rig();
  const a = { chatId: 'c1', text: 'hello', sendId: 'send-0001', tab: { href: 'https://example.com', id: 'tab-1' } };
  await call(r, a);
  await call(r, { ...a, deadline: Date.now() + 10_000, tab: { id: 'tab-1', href: 'https://example.com' } });
  assert.equal(r.calls.filter((c) => c[0] === 'send').length, 1);
  await assert.rejects(call(r, { ...a, skills: ['other'] }), { code: 'send_conflict' });
});

test('ordinary sends persist before admission, retain unknown failures and recheck Stop after the disk wait', async () => {
  let stopped = false;
  let reached = 0;
  const r = rig({
    ops: {
      sendCheck: () => () => {
        if (stopped) throw new Error('stopped before admission');
      },
      send: async (_p: any, check: () => void, admit: () => void) => {
        check();
        admit();
        reached++;
        throw new Error('ack lost');
      },
    },
  });
  let writing = false;
  let release!: () => void;
  const paused = {
    ...fs,
    rename: async (...args: any[]) => {
      if (!writing) {
        writing = true;
        await new Promise<void>((r) => {
          release = r;
        });
      }
      return (fs.rename as any)(...args);
    },
  };
  (r.link.mac as any).sendLedger = new SendLedger({ file: path.join(tempDir(), 'sends.json'), fs: paused });
  const params = { chatId: 'c1', text: 'hello', sendId: 'send-0001' };
  const pending = call(r, params);
  const rejected = assert.rejects(pending, /stopped before admission/);
  await waitFor(() => writing, 'reservation write');
  stopped = true;
  release();
  await rejected;
  assert.equal(reached, 0);
  stopped = false;
  await assert.rejects(call(r, params), { code: 'send_uncertain' });
  for (let n = 0; n < 4; n++) await assert.rejects(call(r, params), { code: 'send_uncertain' });
  assert.equal(reached, 1);
});
