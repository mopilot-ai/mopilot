// The module map (scripts/module-map.mjs): generated from source header comments and never committed, with a
// header comment required on every source file.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import path from 'node:path';
import os from 'node:os';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync, realpathSync, statSync, utimesSync } from 'node:fs';
import { cli, generate, missingHeaders, OUT, render, sourceFiles, summary } from '../scripts/module-map.mjs';

const git = (...args: string[]) => spawnSync('git', args, { encoding: 'utf8' });

test('every source file has a header comment', () => {
  assert.deepEqual(missingHeaders(), [], 'give each of these files a one-line header comment saying what it owns');
});

test('docs/module-map.md is generated, ignored and never committed', () => {
  assert.equal(git('ls-files', '--', OUT).stdout, '', `${OUT} is committed again: git rm --cached ${OUT}`);
  assert.equal(git('check-ignore', '-q', '--', OUT).status, 0, `${OUT} is not in .gitignore`);
  // npm ci writes it (the prepare script), so an agent always has one to read
  const pkg = JSON.parse(readFileSync('package.json', 'utf8'));
  assert.match(pkg.scripts.prepare, /node scripts\/module-map\.mjs/);
  assert.equal(pkg.scripts['module-map'], 'node scripts/module-map.mjs');
});

test('a header is the leading line comments, or a leading block comment set apart from the code', () => {
  assert.equal(summary('// Owns the store. More detail here.\n// And more.\nconst x = 1;'), 'Owns the store.');
  assert.equal(summary("#!/usr/bin/env node\n'use strict';\n// @ts-check\n// Runs the CLI\nmain();"), 'Runs the CLI');
  assert.equal(summary('/**\n * The widget\n * catalog. Extra.\n */\n\nexport const a = 1;'), 'The widget catalog.');
  assert.equal(summary('/** Documents a function. */\nexport function f() {}'), null);
  assert.equal(summary('/* never closed'), null);
  assert.equal(summary('const x = 1;\n// a comment after code'), null);
  assert.equal(summary('//\n//\nx'), null);
  assert.equal(summary(''), null);
  assert.equal(summary("'use strict';"), null);
  assert.equal(summary('/* Only a header. */'), 'Only a header.');
  assert.match(summary(`// ${'word '.repeat(60)}`) ?? '', /^(word ){43}wo\.\.\.$/);
});

test('the map groups files by folder, marks those without a header and holds no whole-tree total', () => {
  assert.equal(
    render([
      ['src/a.ts', 'A.'],
      ['src/b.ts', null],
      ['electron/c.cjs', 'C.'],
    ]),
    [
      '# Module map',
      '',
      "Generated by `npm run module-map` from each file's header comment and not committed; do not edit it. Give a new",
      'file a one-line header comment saying what it owns, and run `npm run module-map` to see it here.',
      '',
      '## src',
      '',
      '- `a.ts`: A.',
      '- `b.ts`: (no header comment)',
      '',
      '## electron',
      '',
      '- `c.cjs`: C.',
      '',
    ].join('\n'),
  );
});

const tree = (t: { after: (fn: () => void) => void }, files: Record<string, string>) => {
  const dir = realpathSync(mkdtempSync(path.join(os.tmpdir(), 'module-map-')));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  for (const [file, text] of Object.entries(files)) {
    mkdirSync(path.join(dir, path.dirname(file)), { recursive: true });
    writeFileSync(path.join(dir, file), text);
  }
  return dir;
};

test('the CLI writes the map, leaves a current one alone, and prints it with --stdout', (t) => {
  const dir = tree(t, {
    'src/a.ts': '// A.\n',
    'src/protocol/P.ts': '// generated\n',
    'src/types.d.ts': '// declarations\n',
    'src/node_modules/x/index.js': '// dependency\n',
    'src/style.css': '',
    'bench/b.mjs': '// B.\n',
  });
  assert.deepEqual(sourceFiles(dir), ['bench/b.mjs', 'src/a.ts']);
  const file = path.join(dir, OUT);
  assert.equal(cli([], { repoRoot: dir }), 0);
  assert.equal(readFileSync(file, 'utf8'), generate(dir));
  assert.match(readFileSync(file, 'utf8'), /- `b\.mjs`: B\.[\s\S]*- `a\.ts`: A\./);
  // unchanged: not rewritten
  const old = new Date(2000, 0, 1);
  utimesSync(file, old, old);
  assert.equal(cli([], { repoRoot: dir }), 0);
  assert.equal(statSync(file).mtime.getTime(), old.getTime());
  writeFileSync(path.join(dir, 'src/a.ts'), '// A changed.\n');
  assert.equal(cli([], { repoRoot: dir }), 0);
  assert.match(readFileSync(file, 'utf8'), /A changed\./);
  const printed: string[] = [];
  assert.equal(cli(['--stdout'], { repoRoot: dir, log: (text: string) => printed.push(text) }), 0);
  assert.deepEqual(printed, [generate(dir)]);
});

test('--check names the source files without a header comment and fails', (t) => {
  const dir = tree(t, { 'src/a.ts': '// A.\n', 'electron/b.cjs': 'x();\n', 'scripts/c.mjs': 'const c = 1;\n' });
  assert.deepEqual(missingHeaders(dir), ['electron/b.cjs', 'scripts/c.mjs']);
  const errors: string[] = [];
  assert.equal(cli(['--check'], { repoRoot: dir, logError: (m: string) => errors.push(m) }), 1);
  assert.match(errors[0], /no header comment[\s\S]*\n {2}electron\/b\.cjs\n {2}scripts\/c\.mjs$/);
  writeFileSync(path.join(dir, 'electron/b.cjs'), '// B.\nx();\n');
  writeFileSync(path.join(dir, 'scripts/c.mjs'), '// C.\nconst c = 1;\n');
  assert.equal(cli(['--check'], { repoRoot: dir }), 0);
  // --check writes nothing
  assert.throws(() => readFileSync(path.join(dir, OUT)));
});

test('the script runs from the command line', () => {
  const run = spawnSync(process.execPath, ['scripts/module-map.mjs', '--check'], { encoding: 'utf8' });
  assert.equal(run.status, 0, run.stderr);
  const printed = spawnSync(process.execPath, ['scripts/module-map.mjs', '--stdout'], { encoding: 'utf8' });
  assert.equal(printed.status, 0);
  assert.equal(printed.stdout, generate());
});

test('hidden folders are not source: a lint-rule fixture written during the run stays out of the map', (t) => {
  const dir = realpathSync(mkdtempSync(path.join(os.tmpdir(), 'module-map-hidden-')));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  mkdirSync(path.join(dir, 'src/.lint-fixture-x'), { recursive: true });
  writeFileSync(path.join(dir, 'src/.lint-fixture-x/view.tsx'), 'export const v = 1;\n');
  writeFileSync(path.join(dir, 'src/a.ts'), '// A.\n');
  assert.deepEqual(sourceFiles(dir), ['src/a.ts']);
});
