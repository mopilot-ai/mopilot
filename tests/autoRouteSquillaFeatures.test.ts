const slice = (a: ArrayLike<number>, from: number, to: number) => Array.from(a).slice(from, to);
const f32 = (values: number[]) => Array.from(Float32Array.from(values));

test('text: canonical text, Python split/strip/len, segments and truncation follow features/text.py', () => {
  assert.equal(text.canonicalizeText(null), '');
  assert.equal(text.canonicalizeText(undefined), '');
  assert.throws(() => text.canonicalizeText(3), /must be str/);
  assert.equal(text.canonicalizeText('\u001c Cafe\u0301\r\nx\ry \u3000'), 'Café\nx\ny');
  assert.deepEqual(text.pySplit(' a\u2003b\u001fc  '), ['a', 'b', 'c']);
  assert.deepEqual(text.pySplit(' \t '), []);
  assert.equal(text.pyLen('a😀b'), 3);
  const seg = text.extractTextSegments({ current_request: ' hi ', history_user: ['1', ' ', '2', '3', '4', '5'], previous_answer: null });
  assert.deepEqual(seg, { current_request: 'hi', recent_history: '2\n[TURN]\n3\n[TURN]\n4\n[TURN]\n5', previous_answer: '' });
  assert.deepEqual(text.segmentTexts(seg), ['hi', seg.recent_history, '']);
  assert.deepEqual(text.extractTextSegments({ current_request: 'x' }).recent_history, '');
  assert.throws(() => text.extractTextSegments({ current_request: '  ' }), /non-empty/);
  assert.throws(() => text.extractTextSegments({ current_request: 'x', history_user: 'nope' }), /sequence of strings/);
  const tokens = [...Array(10).keys()];
  assert.deepEqual(text.truncateContentTokens('current_request', tokens, 4), [0, 1, 2, 9]);
  assert.deepEqual(text.truncateContentTokens('previous_answer', tokens, 4), [0, 1, 8, 9]);
  assert.deepEqual(text.truncateContentTokens('recent_history', tokens, 4), [6, 7, 8, 9]);
  assert.deepEqual(text.truncateContentTokens('previous_answer', tokens, 1), [0]);
  assert.deepEqual(text.truncateContentTokens('current_request', [1, 2]), [1, 2]);
  assert.throws(() => text.truncateContentTokens('other', tokens, 4), /unsupported segment kind/);
  assert.throws(() => text.truncateContentTokens('current_request', tokens, 0), /positive/);
});

