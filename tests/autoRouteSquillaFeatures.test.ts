test('route_history16 projects tiers, trajectories and their validation', () => {
  const h = (...entries: any[]) => Array.from(numeric.extractRouteHistory16(entries));
  const cold = Array.from(numeric.extractRouteHistory16(undefined));
  assert.deepEqual([cold[0], cold[3], cold[6], cold[8]], [-1, -1, -1, 1]);
  assert.equal(h({ tier: 'C2' })[14], 1, 'one entry is unclear');
  assert.equal(h({ tier: 'C0' }, { tier: 'r1' })[9], 1, 'stable low');
  assert.equal(h({ tier_id: 'C2' }, { route_class: 'C3' })[10], 1, 'stable high');
  assert.equal(h({ tier: 'C0', difficulty: 0 }, { tier: 'C1', difficulty: 1 }, { tier: 'C2', difficulty: 2 })[11], 1, 'escalating');
  assert.equal(h({ tier: 'C2', difficulty: 2 }, { tier: 'C1', difficulty: 1 }, { tier: 'C0', difficulty_score: 0 })[12], 1, 'descalating');
  assert.equal(
    h({ tier: 'C0', difficulty: 0 }, { tier: 'C2', difficulty: 2 }, { tier: 'C0', difficulty: 0 }, { tier: 'C2', difficulty: 2 })[13],
    1,
    'oscillating',
  );
  const mixed = h({ tier: 'C0', difficulty: 0 }, { tier: 'C2', difficulty: 0.1, margin: '0.5' }, { tier: 'C2', difficulty: null });
  assert.equal(mixed[15], 1, 'mixed');
  assert.deepEqual(mixed.slice(0, 8), [2, 0, 0, 2, 3, 3, 2, 1]);
  assert.equal(h({ tier: 'C1', difficulty: true, margin: 'abc' })[1], 0);
  assert.throws(() => numeric.extractRouteHistory16('C1'), /must be a sequence/);
  assert.throws(() => numeric.extractRouteHistory16([null]), /must be a mapping/);
  assert.throws(() => numeric.extractRouteHistory16([[1]]), /must be a mapping/);
  assert.throws(() => numeric.extractRouteHistory16([{ tier: 'C9' }]), /invalid tier/);
  assert.throws(() => numeric.extractRouteHistory16([{}]), /invalid tier: undefined/);
});

test('previous_signals19 and context5 read the previous answer, usage and context like Python', () => {
  const previous = 'Could you clarify which file? I cannot help. not sure. `inline code` 1. step one';
  const usage = { input_tokens: '2_000', output_tokens: 300, reasoning_tokens: 'inf', cached_tokens: 5000, duration_ms: false };
  const p = Array.from(numeric.extractPreviousSignals19('继续', previous, usage));
  assert.deepEqual(p.slice(0, 6), [1, 1, 1, 1, 1, 0], 'clarify, refusal, self-doubt and code; a step only at a line start');
  assert.equal(p[7], 0, 'non-finite reasoning tokens count as zero');
  assert.equal(p[8], 0, 'a boolean duration counts as zero');
  assert.equal(p[11], 1, 'cached share is capped at one');
  assert.equal(p[12], 1, 'a short continuation request');
  const none = Array.from(numeric.extractPreviousSignals19('why? compare A?', '', null));
  assert.deepEqual(none.slice(0, 12), new Array(12).fill(0));
  assert.deepEqual(none.slice(14, 16), f32([1, Math.min((2 / 15) * 20, 1)]));
  assert.throws(() => numeric.extractPreviousSignals19('x', '', []), /mapping or null/);
  assert.throws(() => numeric.extractPreviousSignals19('x', '', 'usage'), /mapping or null/);
  const ctx = (input: any) => Array.from(numeric.extractContext5(input));
  assert.deepEqual(
    ctx({ current_request: '```x```', route_history: [1, 2, 3, 4, 5, 6].map(() => ({ tier: 'C1' })) }),
    f32([0.25, 1 / 20000, 1, 1, 0]),
  );
  assert.deepEqual(ctx({ current_request: 'x', context: { context_tokens_est: 4096.7 } }), f32([0, 4096 / 20000, 0, 0, 1]));
  assert.deepEqual(ctx({ current_request: 'x', context: { context_tokens_est: -5 } }), f32([0, 0, 0, 0, 0]));
  assert.deepEqual(ctx({ current_request: 'abcd', history_user: ['efgh'], previous_answer: 'ijkl' }), f32([0, 3 / 20000, 0, 0, 0]));
  assert.throws(() => numeric.extractContext5({ current_request: 'x', route_history: 'C1' }), /must be a sequence/);
  assert.throws(() => numeric.extractContext5({ current_request: 'x', context: [] }), /mapping or null/);
  assert.throws(() => numeric.extractContext5({ current_request: 'x', context: 'big' }), /mapping or null/);
  assert.throws(() => numeric.extractNumeric88({ current_request: 'x', route_history: [{ tier: 'C1', difficulty: 1e300 }] }), /non-finite/);
});

test('Python float semantics: numbers, underscored strings, specials and junk', () => {
  assert.equal(numeric.pyFloat(2.5), 2.5);
  assert.equal(numeric.pyFloat(' 1_0.5e1 '), 105);
  assert.equal(numeric.pyFloat('.5'), 0.5);
  assert.ok(Number.isNaN(numeric.pyFloat('-Infinity')));
  assert.equal(numeric.pyFloat('1__0'), null);
  assert.equal(numeric.pyFloat({}), null);
  assert.equal(numeric.asNonnegative(true), 0);
  assert.equal(numeric.asNonnegative(-3), 0);
  assert.equal(numeric.asNonnegative(null), 0);
  assert.equal(numeric.finiteNumber(false, 7), 7);
  assert.equal(numeric.finiteNumber('nan', 7), 7);
  assert.equal(numeric.finiteNumber('3'), 3);
});

test('char_wb TF-IDF and SVD100 reproduce the character block of the reference features', () => {
  const tfidf = createTfidf(params.tfidf);
  const svd = createSvd(params.svd);
  for (const c of source.cases) {
    const current = text.extractTextSegments(c.input).current_request;
    assert.deepEqual(Array.from(svd(tfidf.transform(current))), slice(c.features, 64, 164), c.name);
  }
  assert.deepEqual(tfidf.transform('\u0000'), [], 'no known n-gram leaves an empty row');
  assert.deepEqual(charWbNgrams('ab  c', 2, 4), [' a', 'ab', 'b ', ' ab', 'ab ', ' ab ', ' c', 'c ', ' c ']);
  assert.throws(() => createTfidf({ ...params.tfidf, options: { ...params.tfidf.options, analyzer: 'word' } }), /unsupported/);
  assert.throws(() => createTfidf({ ...params.tfidf, idf: new Float64Array(1) }), /sizes differ/);
  assert.throws(() => createSvd({ components: new Float32Array(3), rows: 2, cols: 2 }), /wrong size/);
});

test('PCA, whitening and the float32 scaler with its clip', () => {
  const pca = createPca({
    mean: Float64Array.of(1, 1),
    components: Float64Array.of(1, 0, 0, 2),
    explainedVariance: Float64Array.of(4, 1),
    rows: 2,
    whiten: false,
  });
  assert.deepEqual(Array.from(pca(Float32Array.of(3, 2))), [2, 2]);
  const white = createPca({
    mean: Float64Array.of(1, 1),
    components: Float64Array.of(1, 0, 0, 2),
    explainedVariance: Float64Array.of(4, 1),
    rows: 2,
    whiten: true,
  });
  assert.deepEqual(Array.from(white(Float32Array.of(3, 2))), [1, 2]);
  assert.throws(() => pca(Float32Array.of(1)), /expected 2/);
  assert.throws(
    () =>
      createPca({
        mean: Float64Array.of(0),
        components: Float64Array.of(1, 2),
        explainedVariance: Float64Array.of(1),
        rows: 1,
        whiten: false,
      }),
    /wrong size/,
  );
  const scaler = createScaler({ mean: Float64Array.of(1, 0, 0), scale: Float64Array.of(2, 1, 1), withMean: true, withStd: true, limit: 5 });
  assert.deepEqual(Array.from(scaler(Float32Array.of(5, 100, -100))), [2, 5, -5]);
  const raw = createScaler({ mean: Float64Array.of(1), scale: Float64Array.of(2), withMean: false, withStd: false, limit: 5 });
  assert.deepEqual(Array.from(raw(Float32Array.of(3))), [3]);
  assert.throws(() => scaler(Float32Array.of(1)), /expected 3/);
  assert.throws(
    () => createScaler({ mean: Float64Array.of(1), scale: Float64Array.of(), withMean: true, withStd: true, limit: 5 }),
    /sizes differ/,
  );
  // the real PCA64 takes a 512-wide embedding
  assert.equal(createPca(params.pca)(new Float32Array(512)).length, 64);
});

test('the featurizer assembles the 380-vector in the frozen order and builds the intent numeric88', async () => {
  const embedded: string[] = [];
  const featurizer = createFeaturizer({
    embed: async (t: string, kind: string) => {
      embedded.push(`${kind}:${t}`);
      return new Float32Array(512).fill(kind === 'current_request' ? 1 : 2);
    },
    pca: (x: Float32Array) => new Float32Array(64).fill(x[0]),
    tfidf: createTfidf(params.tfidf),
    svd: createSvd(params.svd),
    scaler: (x: Float32Array) => x.map((v) => v + 1),
  });
  const c = source.cases.find((x) => x.name === 'continue_with_history')!;
  const features = await featurizer.tierFeatures(c.input);
  assert.equal(features.length, FEATURE_DIM);
  assert.deepEqual(slice(features, 0, 64), new Array(64).fill(1));
  for (const [from, to] of [
    [64, 212],
    [276, 292],
    [356, 380],
  ])
    assert.deepEqual(slice(features, from, to), slice(c.features, from, to));
  assert.deepEqual(slice(features, 212, 276), new Array(64).fill(2));
  assert.deepEqual(slice(features, 292, 356), new Array(64).fill(2));
  assert.equal(embedded.length, 3);
  const current = await featurizer.tierFeatures({ current_request: c.input.current_request });
  assert.deepEqual(slice(current, 212, 276), new Array(64).fill(0), 'an empty segment bypasses the encoder');
  const intent = Array.from(featurizer.intentNumeric(c.input, current));
  assert.deepEqual(
    intent.slice(0, 48),
    slice(c.features, 164, 212).map((v) => Math.fround(v + 1)),
  );
  assert.deepEqual(
    intent.slice(48, 88),
    slice(c.features, 276, 292)
      .concat(slice(c.features, 356, 380))
      .map((v) => Math.fround(v + 1)),
  );
  const badPca = createFeaturizer({
    embed: async () => new Float32Array(512),
    pca: () => new Float32Array(3),
    tfidf: createTfidf(params.tfidf),
    svd: createSvd(params.svd),
    scaler: (x: Float32Array) => x,
  });
  await assert.rejects(badPca.tierFeatures({ current_request: 'x' }), /PCA output/);
  const badSvd = createFeaturizer({
    embed: async () => new Float32Array(512),
    pca: () => new Float32Array(64),
    tfidf: createTfidf(params.tfidf),
    svd: () => new Float32Array(3),
    scaler: (x: Float32Array) => x,
  });
  await assert.rejects(badSvd.tierFeatures({ current_request: 'x' }), /SVD output/);
  const nan = createFeaturizer({
    embed: async () => new Float32Array(512),
    pca: () => new Float32Array(64).fill(Number.NaN),
    tfidf: createTfidf(params.tfidf),
    svd: createSvd(params.svd),
    scaler: (x: Float32Array) => x,
  });
  await assert.rejects(nan.tierFeatures({ current_request: 'x' }), /non-finite/);
});
